"""Command-line build for Anlogic TD projects (no GUI).

Usage:
    python td_build.py <project_dir> <prj_name> [--top TOP] [--build-dir DIR]

It creates <build-dir>/<prj_name>.prj from <project_dir>/<prj_name>.al with
paths re-based, writes settings.cfg and runs DefaultFlow.tcl from
read_design to bitgen in a single run directory.
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import time
from pathlib import Path

TD_ROOT = Path(r"D:\Anlogic\TD_6.2.1_Engineer_6.2.168.116")
TD_CLI = TD_ROOT / "bin" / "td_commands_prompt.exe"
FLOW_TCL = TD_ROOT / "doc" / "scripts" / "DefaultFlow.tcl"


def rebase_prj(al_text: str, rel_prefix: str) -> str:
    """Rewrite <File Path="x"> to <File Path="<rel_prefix>/x"> and drop Path attr."""
    al_text = re.sub(r'(<Project Version="\d+" Minor="\d+") Path="[^"]*"', r"\1", al_text)

    def repl(m: re.Match[str]) -> str:
        p = m.group(1).replace("\\", "/")
        if re.match(r"^[A-Za-z]:/", p):
            return f'<File Path="{p}"'
        return f'<File Path="{rel_prefix}/{p}"'

    return re.sub(r'<File Path="([^"]+)"', repl, al_text)


def extract_ip_sdc(al_text: str, project_dir: Path, rel_prefix: str) -> str:
    """Build IpSDCList from .ipc files: '<inst> <rel>/<tcl>' pairs."""
    pairs: list[str] = []
    for m in re.finditer(r'<File Path="([^"]+\.ipc)"', al_text):
        ipc = project_dir / m.group(1)
        if not ipc.exists():
            continue
        txt = ipc.read_text(encoding="utf-8", errors="ignore")
        inst = re.search(r"<inst>([^<]+)</inst>", txt)
        sdc = re.search(r'<SDC_FILE Enable="true">([^<]+)</SDC_FILE>', txt)
        if inst and sdc:
            tcl_rel = f"{rel_prefix}/{Path(m.group(1)).parent.as_posix()}/{sdc.group(1)}"
            pairs.append(f"{inst.group(1)} {tcl_rel}")
    return " ".join(pairs)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("project_dir")
    ap.add_argument("prj_name")
    ap.add_argument("--top", default=None)
    ap.add_argument("--build-dir", default=None)
    ap.add_argument("--end-step", default="bitgen",
                    choices=["read_design", "opt_rtl", "opt_gate", "opt_place", "opt_route", "bitgen"])
    args = ap.parse_args()

    project_dir = Path(args.project_dir).resolve()
    al_file = project_dir / f"{args.prj_name}.al"
    if not al_file.exists():
        print(f"ERROR: {al_file} not found", file=sys.stderr)
        return 2

    build_dir = Path(args.build_dir).resolve() if args.build_dir else project_dir.parent / "build" / args.prj_name
    build_dir.mkdir(parents=True, exist_ok=True)
    rel_prefix = os.path.relpath(project_dir, build_dir).replace("\\", "/")

    al_text = al_file.read_text(encoding="utf-8", errors="ignore")
    top = args.top or re.search(r"<MODULE>([^<]+)</MODULE>", al_text).group(1)
    adc = [f'"{rel_prefix}/{p}"' for p in re.findall(r'<ADC_FILE>.*?</ADC_FILE>', al_text, re.S)
           for p in re.findall(r'<File Path="([^"]+)"', p)]
    sdc = [f'"{rel_prefix}/{p}"' for p in re.findall(r'<SDC_FILE>.*?</SDC_FILE>', al_text, re.S)
           for p in re.findall(r'<File Path="([^"]+)"', p)]
    ip_sdc = extract_ip_sdc(al_text, project_dir, rel_prefix)

    (build_dir / f"{args.prj_name}.prj").write_text(rebase_prj(al_text, rel_prefix), encoding="utf-8")
    settings = [
        "# generated by td_build.py",
        f"set ADCList {{{' '.join(adc)}}}",
        f"set SDCList {{{' '.join(sdc)}}}",
    ]
    if ip_sdc:
        settings.append(f"set IpSDCList {{ {ip_sdc} }}")
    settings += [
        "set area_option -packarea",
        "set arr_filter false",
        "set device_name eagle_s20.db",
        "set drHoldFix on",
        "set package_name EG4S20BG256",
        f"set prj_name {{{args.prj_name}}}",
        "set run_type syn",
        "set start_step read_design",
        f"set end_step {args.end_step}",
        f"set top_model_name {{{top}}}",
        "",
    ]
    (build_dir / "settings.cfg").write_text("\n".join(settings), encoding="utf-8")

    print(f"[td_build] build dir : {build_dir}")
    print(f"[td_build] top       : {top}")
    print(f"[td_build] end_step  : {args.end_step}")
    t0 = time.time()
    log_path = build_dir / "build.log"
    with log_path.open("w", encoding="utf-8", errors="ignore") as log:
        proc = subprocess.run([str(TD_CLI), FLOW_TCL.as_posix()], cwd=build_dir,
                              stdout=log, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL)
    dt = time.time() - t0
    print(f"[td_build] exit={proc.returncode} in {dt:.0f}s, log: {log_path}")

    # Summaries
    for name in (f"{args.prj_name}_phy.area", f"{args.prj_name}_phy.ts", "route_flow.status"):
        p = build_dir / name
        if p.exists():
            print(f"---- {name} ----")
            txt = p.read_text(encoding="utf-8", errors="ignore").splitlines()
            print("\n".join(txt[:32]))
    bit = build_dir / f"{args.prj_name}.bit"
    print(f"[td_build] bit: {bit if bit.exists() else 'NOT GENERATED'}")
    log_txt = log_path.read_text(encoding="utf-8", errors="ignore")
    errs = [l for l in log_txt.splitlines() if re.search(r"\bERROR\b|Error:", l)]
    if errs:
        print("---- errors ----")
        print("\n".join(errs[:20]))
    return 0 if bit.exists() or args.end_step != "bitgen" else 1


if __name__ == "__main__":
    sys.exit(main())
